const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const esbuild = require('esbuild');

async function build() {
    const outdir = path.resolve(__dirname, '../../lib/vendor');
    const result = await esbuild.build({
        absWorkingDir: __dirname,
        entryPoints: ['entry.js'],
        outfile: path.join(outdir, 'turf.min.js'),
        bundle: true,
        minify: true,
        format: 'iife',
        globalName: 'turf',
        platform: 'browser',
        target: 'es2017',
        metafile: true,
        legalComments: 'inline',
        banner: { js: '/*! Turf.js 7.4.0: application subset. Generated by tools/turf/build.cjs. Licenses: turf.LICENSE.txt */' }
    });
    // Include notices for every package actually present in the generated file.
    const packages = new Map();
    for (const input of Object.keys(result.metafile.inputs)) {
        if (!input.includes('node_modules/')) continue;
        let dir = path.dirname(path.resolve(__dirname, input));
        while (!fs.existsSync(path.join(dir, 'package.json'))) dir = path.dirname(dir);
        const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
        packages.set(`${pkg.name}@${pkg.version}`, { dir, pkg });
    }
    const notices = [];
    for (const [name, { dir, pkg }] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
        const licenseFiles = fs.readdirSync(dir).filter(file => /^(licen[cs]e|copying)([.-]|$)/i.test(file));
        const texts = licenseFiles.map(file => fs.readFileSync(path.join(dir, file), 'utf8'));
        if (pkg.name === '@turf/jsts') {
            texts.push('JSTS, copyright Björn Harrtell and contributors.\nSource: https://github.com/Turfjs/turf-jsts\n'
                + fs.readFileSync(path.join(__dirname, 'licenses/JSTS-EDL-1.0.txt'), 'utf8'));
        }
        if (!texts.length) throw new Error(`Missing license text: ${name}`);
        notices.push(`${name} (${pkg.license})\n${texts.join('\n')}`);
    }
    fs.writeFileSync(path.join(outdir, 'turf.LICENSE.txt'), notices.join('\n\n--------------------\n\n'));
    const bytes = fs.readFileSync(path.join(outdir, 'turf.min.js'));
    console.log(`Turf subset: ${bytes.length} bytes; gzip: ${zlib.gzipSync(bytes, { level: 9 }).length} bytes`);
}
build().catch(error => { console.error(error); process.exitCode = 1; });
